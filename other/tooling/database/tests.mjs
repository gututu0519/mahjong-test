import pg from 'pg';
import {readFileSync,writeFileSync,mkdirSync,openSync,closeSync} from 'node:fs';
import {resolve} from 'node:path';
import {tmpdir} from 'node:os';
import {spawn} from 'node:child_process';
import {root} from './inventory.mjs';
import {metadata} from '../../runtime/server/dist/shared/database/migrations.js';
import {isolatedTestEnvironment} from '../../runtime/server/dist/shared/config/environment.js';
const {databaseSettings}=await import('./settings.mjs');
const settings=databaseSettings();
const database='gtt_test_'+Date.now(), admin=new pg.Client({...settings.connection,database:'postgres'});await admin.connect();
await admin.query('CREATE DATABASE "'+database+'" TEMPLATE template0');await admin.end();
const connection={...settings.connection,database};
const client=new pg.Client(connection);await client.connect();await metadata(client);await client.end();
const config=resolve(root,'gateway/instance/data/postgres-tests.json');
writeFileSync(config,JSON.stringify({driver:'postgres',connection,testMode:true,testRoot:tmpdir(),sources:[]},null,2),{mode:0o600});
mkdirSync(resolve(root,'other/diagnostics/postgres'),{recursive:true});
const path=resolve(root,'other/diagnostics/postgres',database+'.log'),fd=openSync(path,'w');
const selected=process.argv.slice(2);
const files=(selected.length?selected:['all']).map(n=>n==='all'?'dist/tests/*.test.js':'dist/tests/'+n+'.test.js');
const child=spawn(process.execPath,['--test','--test-concurrency=1',...files],{cwd:resolve(root,'other/runtime/server'),env:{...isolatedTestEnvironment(process.env),GTT_PG_CONFIG:config},stdio:['ignore',fd,fd]});
const code=await new Promise((ok,fail)=>{child.on('error',fail);child.on('exit',ok);});closeSync(fd);
console.log(`PostgreSQL test database: ${database}; exit ${code}; full log: ${path}`);process.exitCode=code??1;
